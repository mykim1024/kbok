-- V8__add_interpretation_schema.sql

-- 1. 타자 기록: 타율(KBO 공식 값), 주루
ALTER TABLE batter_stat
    ADD COLUMN avg NUMERIC(4,3) NOT NULL DEFAULT 0,
    ADD COLUMN sb  INTEGER      NOT NULL DEFAULT 0,
    ADD COLUMN cs  INTEGER      NOT NULL DEFAULT 0;

-- 2. 투수 기록: 계산용 이닝(아웃카운트), 평균자책점·WHIP(KBO 공식 값)
--    이닝이 0이면 KBO에서도 값이 "-"라 era, whip은 NULL 허용
ALTER TABLE pitcher_stat
    ADD COLUMN innings_outs INTEGER NOT NULL DEFAULT 0,
    ADD COLUMN era          NUMERIC(5,2),
    ADD COLUMN whip         NUMERIC(4,2);

-- 3. 중복 방지: 선수 한 명당 시즌 기록 한 줄
ALTER TABLE batter_stat
    ADD CONSTRAINT uk_batter_stat_player_season UNIQUE (player_id, season);
ALTER TABLE pitcher_stat
    ADD CONSTRAINT uk_pitcher_stat_player_season UNIQUE (player_id, season);

-- 4. 수비 기록 (참고용, 포지션 단위) - 엔티티는 수비 크롤러 작업 때 추가
CREATE TABLE fielding_stat (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_id    BIGINT       NOT NULL REFERENCES player(id),
    team_id      BIGINT       NOT NULL REFERENCES team(id),
    season       INTEGER      NOT NULL,
    position     VARCHAR(10)  NOT NULL,
    games        INTEGER      NOT NULL DEFAULT 0,
    errors       INTEGER      NOT NULL DEFAULT 0,
    fielding_pct NUMERIC(4,3),
    is_active    BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_fielding_stat_player_season_pos UNIQUE (player_id, season, position)
);

-- 5. 검색용 인덱스: 시즌·팀으로 선수 목록을 거르는 조회가 가장 많다
CREATE INDEX idx_batter_stat_season_team  ON batter_stat  (season, team_id);
CREATE INDEX idx_pitcher_stat_season_team ON pitcher_stat (season, team_id);
